"""Generate locally hosted, on-demand font shards from the official full Noto Serif SC.

Uses the existing FontTools and Node.js; installs nothing and never reads archive records.
Example: python -X utf8 site/scripts/subset-complete-font.py --source /path/NotoSerifSC.ttf
"""
import argparse
import hashlib
import io
import json
import shutil
import subprocess
import sys
import types
from pathlib import Path

parser = argparse.ArgumentParser()
parser.add_argument("--source", required=True, type=Path)
parser.add_argument("--node", default=shutil.which("node"))
args = parser.parse_args()
if not args.node:
    raise SystemExit("Existing Node.js is required for Brotli compression.")

def codec(data, compress=False):
    operation = "brotliCompressSync" if compress else "brotliDecompressSync"
    options = ",{params:{[z.constants.BROTLI_PARAM_MODE]:z.constants.BROTLI_MODE_FONT}}" if compress else ""
    program = (
        "const z=require('node:zlib');const chunks=[];"
        "process.stdin.on('data',c=>chunks.push(c));"
        "process.stdin.on('end',()=>process.stdout.write(z."
        + operation + "(Buffer.concat(chunks)" + options + ")));"
    )
    return subprocess.run([args.node, "-e", program], input=data, capture_output=True, check=True).stdout

bridge = types.ModuleType("brotli")
bridge.decompress = lambda data: codec(data)
bridge.compress = lambda data, **options: codec(data, True)
bridge.MODE_FONT = 2
sys.modules["brotli"] = bridge
from fontTools import subset
from fontTools.ttLib import TTFont

font_root = Path(__file__).resolve().parent.parent / "src/assets/fonts"
source_bytes = args.source.read_bytes()
source = TTFont(io.BytesIO(source_bytes))
axes = [(axis.axisTag, axis.minValue, axis.defaultValue, axis.maxValue) for axis in source["fvar"].axes]
if axes != [("wght", 200.0, 200.0, 900.0)]:
    raise SystemExit(f"Unexpected variable weight axes: {axes}")
family = source["name"].getDebugName(1)
if not family or not family.startswith("Noto Serif SC"):
    raise SystemExit("Source must be the same Noto Serif SC family.")
available = set(source.getBestCmap())
required_han = set(range(0x3400, 0x4DC0)) | set(range(0x4E00, 0xA000))
if required_han - available:
    raise SystemExit("Source must contain the complete basic CJK and Extension A blocks.")
legacy = set()
for filename in ["noto-serif-sc-brand.woff2", "noto-serif-sc-public-supplement.woff2", "noto-serif-sc-brand-supplement.woff"]:
    legacy.update(TTFont(font_root / filename).getBestCmap())

def ranges_of(points):
    ranges = []
    for point in sorted(points):
        if ranges and point == ranges[-1][1] + 1:
            ranges[-1][1] = point
        else:
            ranges.append([point, point])
    return ranges

def css_range(ranges):
    return ", ".join(f"U+{start:X}" if start == end else f"U+{start:X}-{end:X}" for start, end in ranges)

groups = {}
for point in sorted(available - legacy):
    groups.setdefault(point // 256, set()).add(point)
output = font_root / "complete"
output.mkdir(exist_ok=True)
manifest = {
    "source_url": "https://raw.githubusercontent.com/google/fonts/main/ofl/notoserifsc/NotoSerifSC%5Bwght%5D.ttf",
    "source_sha256": hashlib.sha256(source_bytes).hexdigest(),
    "version": source["name"].getDebugName(5),
    "source_character_count": len(available),
    "source_ranges": ranges_of(available),
    "weight_range": [200, 900],
    "bucket_size": 256,
    "shards": [],
}
styles = ["/* Generated by scripts/subset-complete-font.py; full font coverage, loaded only when needed. */"]
for index, (bucket, points) in enumerate(sorted(groups.items()), 1):
    font = TTFont(io.BytesIO(source_bytes))
    options = subset.Options()
    options.name_IDs = ["*"]
    options.layout_features = ["*"]
    cutter = subset.Subsetter(options=options)
    cutter.populate(unicodes=points)
    cutter.subset(font)
    if set(font.getBestCmap()) != points:
        raise SystemExit(f"Shard {bucket:X} character mappings changed unexpectedly.")
    font.flavor = "woff2"
    filename = f"noto-serif-sc-full-{bucket:04x}.woff2"
    font.save(output / filename)
    data = (output / filename).read_bytes()
    ranges = ranges_of(points)
    manifest["shards"].append({"file": filename, "sha256": hashlib.sha256(data).hexdigest(), "bytes": len(data), "ranges": ranges})
    styles.append(
        "@font-face {\n  font-family: 'LJM Brand Serif';\n"
        f"  src: url('./{filename}') format('woff2');\n"
        "  font-style: normal;\n  font-weight: 200 900;\n  font-display: swap;\n"
        f"  unicode-range: {css_range(ranges)};\n}}"
    )
    print(f"{index}/{len(groups)} {filename}: {len(points)} characters, {len(data)} bytes", flush=True)
(output / "complete.css").write_text("\n\n".join(styles) + "\n", encoding="utf-8")
(output / "manifest.json").write_text(json.dumps(manifest, indent=2) + "\n", encoding="utf-8")
print(f"Complete source: {len(available)} characters; supplement shards: {sum(len(points) for points in groups.values())}; total bytes: {sum(shard['bytes'] for shard in manifest['shards'])}", flush=True)
