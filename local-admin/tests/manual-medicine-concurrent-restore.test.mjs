import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import {createManualHttpFixture} from './helpers/manuals-http-fixture.mjs';
import {manualFixtureCatalog} from './helpers/manuals-fixture.mjs';

test('两位维护者同时编辑药品和物件时只接收一份；重新核对后两类修改和恢复前草稿均可找回',async t=>{
  const f=await createManualHttpFixture(t);
  const status=async()=>(await f.get('/api/manuals')).body;
  const save=(catalog,expectedRevision)=>f.post('/api/manuals/save',{catalog,expectedRevision,medicineDraftVersion:1});
  const restore=(history_id,expectedRevision)=>f.post('/api/manuals/restore',{history_id,expectedRevision,medicineDraftVersion:1});
  const catalog=manualFixtureCatalog();
  catalog.schema_version=2;
  catalog.medicines=[{medicine_key:'medicine-a',generic_name:'合成药品甲',strength:'合成规格甲',legacy_model_key:'model-old'}];
  catalog.models.push({...catalog.models[0],model_key:'model-old',model_text:'合成旧目录',model_aliases:[],category_key:'medicines'});
  catalog.documents.push({...structuredClone(catalog.documents[0]),manual_key:'manual-old',model_keys:['model-old']});
  catalog.documents.push({...structuredClone(catalog.documents[0]),manual_key:'manual-drug',model_keys:[],medicine_keys:['medicine-a']});
  assert.equal((await save(catalog,(await status()).revision)).status,200);
  const ready=await status();
  const report=await f.post('/api/manuals/review',{expectedRevision:ready.revision});
  assert.deepEqual(report.body.issues,[]);
  const published=await f.post('/api/manuals/publish',{expectedRevision:ready.revision,review_id:report.body.review_id,confirmations:Array(5).fill(true)});
  assert.equal(published.status,200,JSON.stringify(published.body));
  const source=await fs.readFile(f.source);
  const initial=await status();
  const seed=structuredClone(initial.state.published);
  seed.medicines[0].trade_name='草稿初值';
  assert.equal((await save(seed,initial.revision)).status,200);
  const baseline=await status();
  const first=structuredClone(baseline.state.draft),second=structuredClone(baseline.state.draft);
  const changeDrug=data=>{data.medicines[0].trade_name='药品新录入的商品名';};
  const changeObject=data=>{data.documents.find(doc=>doc.manual_key==='manual-test').edition_display='物件新录入的版本';};
  changeDrug(first);
  changeObject(second);
  const writes=await Promise.all([save(first,baseline.revision),save(second,baseline.revision)]);
  assert.deepEqual(writes.map(r=>r.status).sort(),[200,409],JSON.stringify(writes));
  const winner=await status();
  assert.deepEqual(winner.state.draft,writes[0].status===200?first:second);
  const previous=winner.history.find(row=>row.kind==='draft-before-save');
  assert(previous);
  const combined=structuredClone(winner.state.draft);
  if(writes[0].status===200)changeObject(combined);else changeDrug(combined);
  assert.equal((await save(combined,winner.revision)).status,200);
  const both=await status();
  assert.deepEqual(both.state.draft,combined);
  assert.equal(both.state.draft.medicines[0].trade_name,'药品新录入的商品名');
  assert.equal(both.state.draft.documents.find(doc=>doc.manual_key==='manual-test').edition_display,'物件新录入的版本');
  assert.equal((await restore(previous.history_id,baseline.revision)).status,409);
  assert.deepEqual((await status()).state.draft,combined);

  assert.equal((await restore(previous.history_id,both.revision)).status,200);
  const restored=await status();
  assert.deepEqual(restored.state.draft,baseline.state.draft);
  const recovery=restored.history.find(row=>row.kind==='draft-before-restore');
  assert(recovery);
  assert.equal((await restore(recovery.history_id,restored.revision)).status,200);
  const recovered=await status();
  assert.deepEqual(recovered.state.draft,combined);
  assert.deepEqual(recovered.state.published,initial.state.published);
  assert.deepEqual(await fs.readFile(f.source),source);
});
